import { readdir, readFile, writeFile } from "node:fs/promises";

const validateUrl = new URL("./validate.mjs", import.meta.url);
let source = await readFile(validateUrl, "utf8");

const buildAssertionBefore = 'includes(buildCore, "modules/app-core-runtime.js", "The core build must write the generated shared runtime artifact.");';
const buildAssertionAfter = 'includes(buildCore, \'runtime: "app-core-runtime.js"\', "The core build must write the generated shared runtime artifact.");';
if (!source.includes(buildAssertionBefore)) throw new Error("Source-owned core runtime build assertion was not found.");
source = source.replace(buildAssertionBefore, buildAssertionAfter);

const coreAliasBefore = "const coreSource = canonicalSharedCore;";
const coreAliasAfter = `const coreSource = [
  canonicalSharedCore,
  await readSite("modules/core-sources/evaluation.js"),
  await readSite("modules/core-sources/mfl-stats.js"),
  await readSite("modules/core-sources/club.js"),
  await readSite("modules/core-sources/settings.js"),
  await readSite("modules/core-sources/player.js"),
  await readSite("modules/core-sources/table.js"),
  await readSite("modules/core-sources/wallet.js"),
  await readSite("modules/core-sources/watchlist.js"),
].join("\\n");`;
if (!source.includes(coreAliasBefore)) throw new Error("Shared-core validator alias was not found.");
source = source.replace(coreAliasBefore, coreAliasAfter);

const legacyHeaderAssertion = 'includes(coreSource, "buildHeader.__mflSingleRenderOwner", "Canonical app-core must make buildHeader the single persistent header owner.");\n';
if (!source.includes(legacyHeaderAssertion)) throw new Error("Legacy monolith-only header assertion was not found.");
source = source.replace(legacyHeaderAssertion, "");
await writeFile(validateUrl, source, "utf8");

const generatedCores = Object.freeze([
  Object.freeze({ key: "evaluation", variable: "evaluationRuntimePath", runtime: "app-core-evaluation-runtime.js", source: "evaluation.js", label: "Evaluation" }),
  Object.freeze({ key: "mflstats", variable: "mflStatsRuntimePath", runtime: "app-core-mfl-stats-runtime.js", source: "mfl-stats.js", label: "MFL Stats" }),
  Object.freeze({ key: "club", variable: "clubRuntimePath", runtime: "app-core-club-runtime.js", source: "club.js", label: "Club" }),
  Object.freeze({ key: "settings", variable: "settingsRuntimePath", runtime: "app-core-settings-runtime.js", source: "settings.js", label: "Settings" }),
  Object.freeze({ key: "player", variable: "playerRuntimePath", runtime: "app-core-player-runtime.js", source: "player.js", label: "Player" }),
  Object.freeze({ key: "table", variable: "tableRuntimePath", runtime: "app-core-table-runtime.js", source: "table.js", label: "Table" }),
  Object.freeze({ key: "wallet", variable: "walletRuntimePath", runtime: "app-core-wallet-runtime.js", source: "wallet.js", label: "Wallet" }),
  Object.freeze({ key: "watchlist", variable: "watchlistRuntimePath", runtime: "app-core-watchlist-runtime.js", source: "watchlist.js", label: "Watchlist" }),
]);

const bannerReplacements = new Map([
  ["// Generated by build-app-core.mjs from modules/app-core.js. Do not edit directly.\\n", "// Generated by build-app-core.mjs from modules/core-sources/shared.js. Do not edit directly.\\n"],
  ...generatedCores.map((entry) => [
    `// Generated ${entry.label} core chunk from modules/app-core.js. Do not edit directly.\\n`,
    `// Generated ${entry.label} core from modules/core-sources/${entry.source}. Do not edit directly.\\n`,
  ]),
]);

const names = (await readdir(new URL("./", import.meta.url)))
  .filter((name) => /^validate.*\.mjs$/.test(name));

for (const name of names) {
  const url = new URL(`./${name}`, import.meta.url);
  let text = await readFile(url, "utf8");
  const original = text;

  for (const [before, after] of bannerReplacements) text = text.replaceAll(before, after);

  for (const entry of generatedCores) {
    const oldRuntimeLiteral = `const ${entry.variable} = resolve(siteRoot, "modules/${entry.runtime}");`;
    const newRuntimeLiteral = `runtime: "${entry.runtime}"`;
    text = text.replaceAll(oldRuntimeLiteral, newRuntimeLiteral);
    text = text.replaceAll(`"artifacts.routeChunks?.${entry.key}"`, `'source: "${entry.source}"'`);
    text = text.replaceAll(`'artifacts.routeChunks?.${entry.key}'`, `'source: "${entry.source}"'`);
  }

  text = text.replaceAll(
    'artifact.includes("function tableTooltipTarget(event)") || artifact.includes("showPlayerNoteTooltip(tooltip)")',
    'source.includes("function tableTooltipTarget(event)") || source.includes("showPlayerNoteTooltip(tooltip)")',
  );
  text = text.replaceAll(
    'artifact.includes("__mflTooltipSettings?.gap") || artifact.includes("anchorHeight = 14")',
    'source.includes("__mflTooltipSettings?.gap") || source.includes("anchorHeight = 14")',
  );
  text = text.replaceAll(
    "Generated application core does not position manual tooltips from the real generator rectangle.",
    "Canonical application core does not position manual tooltips from the real generator rectangle.",
  );

  if (text !== original) await writeFile(url, text, "utf8");
}

