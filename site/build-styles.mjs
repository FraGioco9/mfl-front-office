import { readFile, writeFile } from "node:fs/promises";

const importedStyles = Object.freeze([
  "styles-base.css",
  "scrollbars.css",
  "dropdowns.css",
  "controls.css",
  "footer.css",
  "loading.css",
]);
const importPrefix = `${importedStyles.map((name) => `@import url("/${name}");`).join("\n")}\n`;
const normalize = (value) => String(value).replace(/\r\n?/g, "\n");
const read = async (path) => normalize(await readFile(new URL(path, import.meta.url), "utf8"));

const styles = await read("./styles.css");
if (!styles.startsWith(importPrefix)) {
  throw new Error("styles.css must keep the canonical import prefix before production CSS can be bundled.");
}

const importedSources = await Promise.all(importedStyles.map((name) => read(`./${name}`)));
const rootStyles = styles.slice(importPrefix.length).replace(/^\n+/, "");
const sections = [
  ...importedStyles.map((name, index) => `/* Source: ${name} */\n${importedSources[index].trimEnd()}\n`),
  `/* Source: styles.css */\n${rootStyles.trimEnd()}\n`,
];
const bundle = `/* Generated by build-styles.mjs. Edit canonical CSS sources instead. */\n${sections.join("\n")}`;
await writeFile(new URL("./styles-runtime.css", import.meta.url), bundle, "utf8");

const indexUrl = new URL("./index.html", import.meta.url);
const index = await readFile(indexUrl, "utf8");
const sourceLink = '<link rel="stylesheet" href="/styles.css">';
const runtimeLink = '<link rel="stylesheet" href="/styles-runtime.css">';
const sourceLinkCount = String(index).split(sourceLink).length - 1;
const runtimeLinkCount = String(index).split(runtimeLink).length - 1;
if (sourceLinkCount > 1 || runtimeLinkCount > 1 || (sourceLinkCount === 0 && runtimeLinkCount === 0)) {
  throw new Error("index.html must contain exactly one canonical primary stylesheet link.");
}
if (sourceLinkCount === 1) {
  await writeFile(indexUrl, String(index).replace(sourceLink, runtimeLink), "utf8");
}
