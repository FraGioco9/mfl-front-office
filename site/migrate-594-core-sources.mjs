import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const siteRoot = dirname(fileURLToPath(import.meta.url));
const modulesRoot = resolve(siteRoot, "modules");
const sourceRoot = resolve(modulesRoot, "core-sources");

const sourcePairs = [
  ["app-core-runtime.js", "shared.js"],
  ["app-core-evaluation-runtime.js", "evaluation.js"],
  ["app-core-mfl-stats-runtime.js", "mfl-stats.js"],
  ["app-core-club-runtime.js", "club.js"],
  ["app-core-settings-runtime.js", "settings.js"],
  ["app-core-player-runtime.js", "player.js"],
  ["app-core-table-runtime.js", "table.js"],
  ["app-core-wallet-runtime.js", "wallet.js"],
  ["app-core-watchlist-runtime.js", "watchlist.js"],
];

function stripGeneratedBanner(source) {
  const normalized = String(source || "").replace(/\r\n?/g, "\n");
  return normalized.replace(/^\/\/ Generated[^\n]*\n/, "").replace(/\s*$/, "") + "\n";
}

await mkdir(sourceRoot, { recursive: true });
for (const [runtimeName, sourceName] of sourcePairs) {
  const runtime = await readFile(resolve(modulesRoot, runtimeName), "utf8");
  await writeFile(resolve(sourceRoot, sourceName), stripGeneratedBanner(runtime), "utf8");
}

const buildSource = `import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { browserConfigRuntimeSource } from "./modules/app-config.js";
import { normalizePreBootstrapRouteState } from "./modules/pre-bootstrap-route-state.js";
import { synchronizeReleaseProjections } from "./sync-release-projections.mjs";

const siteRoot = dirname(fileURLToPath(import.meta.url));
const releasePath = resolve(siteRoot, "release.json");
const tableWidthRuntimePath = resolve(siteRoot, "table-width-runtime.js");

const CORE_SOURCES = Object.freeze([
  Object.freeze({ source: "shared.js", runtime: "app-core-runtime.js", banner: "// Generated by build-app-core.mjs from modules/core-sources/shared.js. Do not edit directly.\\n" }),
  Object.freeze({ source: "evaluation.js", runtime: "app-core-evaluation-runtime.js", banner: "// Generated Evaluation core from modules/core-sources/evaluation.js. Do not edit directly.\\n" }),
  Object.freeze({ source: "mfl-stats.js", runtime: "app-core-mfl-stats-runtime.js", banner: "// Generated MFL Stats core from modules/core-sources/mfl-stats.js. Do not edit directly.\\n" }),
  Object.freeze({ source: "club.js", runtime: "app-core-club-runtime.js", banner: "// Generated Club core from modules/core-sources/club.js. Do not edit directly.\\n" }),
  Object.freeze({ source: "settings.js", runtime: "app-core-settings-runtime.js", banner: "// Generated Settings core from modules/core-sources/settings.js. Do not edit directly.\\n" }),
  Object.freeze({ source: "player.js", runtime: "app-core-player-runtime.js", banner: "// Generated Player core from modules/core-sources/player.js. Do not edit directly.\\n" }),
  Object.freeze({ source: "table.js", runtime: "app-core-table-runtime.js", banner: "// Generated Table core from modules/core-sources/table.js. Do not edit directly.\\n" }),
  Object.freeze({ source: "wallet.js", runtime: "app-core-wallet-runtime.js", banner: "// Generated Wallet core from modules/core-sources/wallet.js. Do not edit directly.\\n" }),
  Object.freeze({ source: "watchlist.js", runtime: "app-core-watchlist-runtime.js", banner: "// Generated Watchlist core from modules/core-sources/watchlist.js. Do not edit directly.\\n" }),
]);

async function writeFileIfChanged(path, content) {
  let current = null;
  try {
    current = await readFile(path, "utf8");
  } catch (error) {
    if (!(error instanceof Error) || !("code" in error) || error.code !== "ENOENT") throw error;
  }
  if (current === content) return false;
  await writeFile(path, content, "utf8");
  return true;
}

await synchronizeReleaseProjections(siteRoot);

const release = JSON.parse(await readFile(releasePath, "utf8"));
const appConfigRuntime = normalizePreBootstrapRouteState(browserConfigRuntimeSource(release)).replace(/\\s*$/, "");
if (!appConfigRuntime) throw new Error("Canonical app configuration produced an empty browser runtime.");
const preBootstrapRuntime = \`\${appConfigRuntime}\\nwindow.__mflUniformWidth = Object.freeze({\\n  name: "Uniform Width",\\n  source: "styles.css",\\n  unit: "%",\\n});\`;

const artifacts = [];
for (const entry of CORE_SOURCES) {
  const sourcePath = resolve(siteRoot, "modules", "core-sources", entry.source);
  const runtimePath = resolve(siteRoot, "modules", entry.runtime);
  const source = String(await readFile(sourcePath, "utf8")).replace(/\\r\\n?/g, "\\n").replace(/\\s*$/, "");
  if (!source) throw new Error(\`Canonical core source is empty: \${entry.source}.\`);
  artifacts.push(Object.freeze({ ...entry, sourcePath, runtimePath, source }));
}

if (!artifacts.some(({ source }) => source.includes('icon: "calendar-x-2"'))) {
  throw new Error("Canonical core sources do not use the calendar-x-2 icon for retired players.");
}
if (!artifacts.some(({ source }) => source.includes('icon: "calendar-clock"'))) {
  throw new Error("Canonical core sources do not use the calendar-clock icon for retiring players.");
}
if (!artifacts.some(({ source }) => source.includes("\`/retirement-\${marker.icon}.svg\`"))) {
  throw new Error("Canonical core sources do not render retirement marker SVG assets.");
}
const playerSource = artifacts.find(({ source: sourceName }) => sourceName === "player.js")?.source || "";
if (!playerSource.includes('ageMarker.icon)}.svg')) {
  throw new Error("Canonical Player core source does not render retirement SVG markers.");
}

for (const { sourcePath, source } of artifacts) {
  if (source.includes("window.eval") || source.includes("eval(")) {
    throw new Error(\`String evaluation leaked into canonical application core: \${sourcePath}.\`);
  }
  if (source.includes("__mflEvaluationRouteStability") || source.includes("evaluationRouteStabilityStyles")) {
    throw new Error(\`Legacy Evaluation route-stability ownership leaked into canonical application core: \${sourcePath}.\`);
  }
  if (source.includes("__mflTooltipSettings?.gap") || source.includes("anchorHeight = 14")) {
    throw new Error(\`Legacy tooltip spacing ownership leaked into canonical application core: \${sourcePath}.\`);
  }
  if (source.includes("function tableTooltipTarget(event)") || source.includes("showPlayerNoteTooltip(tooltip)")) {
    throw new Error(\`Delegated table tooltip ownership leaked outside the global Tooltip Height runtime: \${sourcePath}.\`);
  }
}
if (!artifacts.some(({ source }) => source.includes("iconRect.top - tooltipRect.height - tooltipHeight"))) {
  throw new Error("Canonical application core does not position manual tooltips from the real generator rectangle.");
}

const tableWidthChanged = await writeFileIfChanged(tableWidthRuntimePath, \`\${preBootstrapRuntime}\\n\`);
const runtimeChanges = await Promise.all(artifacts.map(({ runtimePath, banner, source }) => (
  writeFileIfChanged(runtimePath, \`\${banner}\${source}\\n\`)
)));

if (process.env.MFL_BUILD_VERBOSE === "1") {
  console.log(\`\${tableWidthChanged ? "Generated" : "Unchanged"} \${tableWidthRuntimePath} (canonical config + Uniform Width).\`);
  artifacts.forEach(({ runtimePath, source }, index) => {
    console.log(\`\${runtimeChanges[index] ? "Generated" : "Unchanged"} \${runtimePath} (\${Buffer.byteLength(source, "utf8")} source-owned bytes).\`);
  });
}
`;

await writeFile(resolve(siteRoot, "build-app-core.mjs"), buildSource, "utf8");
console.log("Promoted generated application-core artifacts to canonical split source modules.");
