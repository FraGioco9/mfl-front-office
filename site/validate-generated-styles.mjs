import { readFile } from "node:fs/promises";

const importedStyles = Object.freeze([
  "styles-base.css",
  "scrollbars.css",
  "dropdowns.css",
  "controls.css",
  "footer.css",
  "loading.css",
]);
const normalize = (value) => String(value).replace(/\r\n?/g, "\n");
const read = async (path) => normalize(await readFile(new URL(path, import.meta.url), "utf8"));
const invariant = (condition, message) => {
  if (!condition) throw new Error(message);
};

const [styles, runtimeStyles, index, packageJson, vercelIgnore] = await Promise.all([
  read("./styles.css"),
  read("./styles-runtime.css"),
  read("./index.html"),
  read("./package.json"),
  read("../.vercelignore"),
]);
const importedSources = await Promise.all(importedStyles.map((name) => read(`./${name}`)));
const importPrefix = `${importedStyles.map((name) => `@import url("/${name}");`).join("\n")}\n`;
invariant(styles.startsWith(importPrefix), "Canonical styles.css import order must remain stable for deterministic bundling.");

const rootStyles = styles.slice(importPrefix.length).replace(/^\n+/, "");
const expected = `/* Generated by build-styles.mjs. Edit canonical CSS sources instead. */\n${[
  ...importedStyles.map((name, indexValue) => `/* Source: ${name} */\n${importedSources[indexValue].trimEnd()}\n`),
  `/* Source: styles.css */\n${rootStyles.trimEnd()}\n`,
].join("\n")}`;
invariant(runtimeStyles === expected, "styles-runtime.css must exactly match the canonical CSS source cascade.");
invariant(
  index.includes('<link rel="stylesheet" href="/styles-runtime.css">')
    && !index.includes('<link rel="stylesheet" href="/styles.css">'),
  "Production HTML must serve the bundled primary stylesheet instead of the @import source entrypoint.",
);
invariant(
  packageJson.includes('"build:styles": "node build-styles.mjs"')
    && packageJson.includes('"build": "npm run build:core && npm run build:styles"')
    && packageJson.includes("styles-runtime.css table-width-runtime.js"),
  "The normal build and generated verification paths must own styles-runtime.css.",
);
invariant(
  vercelIgnore.includes("site/build-styles.mjs"),
  "The stylesheet compiler must remain build-only in the Vercel artifact.",
);

console.log("Generated production stylesheet validation passed.");
