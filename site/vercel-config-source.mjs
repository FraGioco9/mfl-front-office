const commonHeaders = Object.freeze([
  Object.freeze({ source: "/", headers: [Object.freeze({ key: "Cache-Control", value: "no-store, max-age=0" })] }),
  Object.freeze({ source: "/index.html", headers: [Object.freeze({ key: "Cache-Control", value: "no-store, max-age=0" })] }),
  Object.freeze({ source: "/release.json", headers: [Object.freeze({ key: "Cache-Control", value: "no-store, max-age=0" })] }),
  Object.freeze({ source: "/releases.json", headers: [Object.freeze({ key: "Cache-Control", value: "no-store, max-age=0" })] }),
]);

const functions = Object.freeze({
  "api/data.js": Object.freeze({ includeFiles: "api/data-files/mfl_database.db", maxDuration: 60 }),
  "api/evaluation-preview.js": Object.freeze({ includeFiles: "{index.html,api/data-files/mfl_database.db}" }),
  "api/evaluation-preview-image.js": Object.freeze({ includeFiles: "{api/data-files/mfl_database.db,node_modules/@expo-google-fonts/titillium-web/**/*.ttf,node_modules/webp-wasm/webp_node_dec.wasm}" }),
  "api/progression-email-portrait.js": Object.freeze({ includeFiles: "node_modules/webp-wasm/webp_node_dec.wasm" }),
});

const rewrites = Object.freeze([
  Object.freeze({ source: "/releases.json", destination: "/api/releases" }),
  Object.freeze({ source: "/evaluation", destination: "/api/evaluation-preview" }),
  Object.freeze({ source: "/(.*)", destination: "/" }),
]);

const cssHeader = Object.freeze({
  source: "/(.*\\.css)",
  headers: [Object.freeze({ key: "Cache-Control", value: "public, max-age=0, must-revalidate" })],
});

const developmentJsHeaders = Object.freeze([
  Object.freeze({
    source: "/(.*\\.js)",
    headers: [Object.freeze({ key: "Cache-Control", value: "no-store, max-age=0" })],
  }),
]);

const productionJsHeaders = Object.freeze([
  Object.freeze({
    source: "/(.*\\.js)",
    missing: [Object.freeze({ type: "query", key: "mfl_core" })],
    headers: [Object.freeze({ key: "Cache-Control", value: "no-store, max-age=0" })],
  }),
  Object.freeze({
    source: "/modules/app-core-runtime.js",
    has: [Object.freeze({ type: "query", key: "mfl_core" })],
    headers: [Object.freeze({ key: "Cache-Control", value: "public, max-age=31536000, immutable" })],
  }),
]);

export function createVercelConfig({ production = false } = {}) {
  return {
    $schema: "https://openapi.vercel.sh/vercel.json",
    buildCommand: "echo \"Using prebuilt application core generated by GitHub Actions\"",
    outputDirectory: ".",
    functions,
    headers: [
      ...commonHeaders,
      ...(production ? productionJsHeaders : developmentJsHeaders),
      cssHeader,
    ],
    rewrites,
  };
}

export function serializeVercelConfig(options = {}) {
  return `${JSON.stringify(createVercelConfig(options), null, 2)}\n`;
}
