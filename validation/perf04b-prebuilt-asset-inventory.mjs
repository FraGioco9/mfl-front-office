// Read-only PERF-04B inventory of *actual* vercel build output static assets.
// Called only after a build-only Vercel CLI run; no production/network writes.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, readdir } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(process.argv[2] || ".vercel/output");
const [configSource, generated, emitted, topFiles] = await Promise.all([
  readFile(resolve(root, "config.json"), "utf8"),
  readFile(resolve("styles-runtime.css")),
  readFile(resolve(root, "static/styles-runtime.css")),
  readdir(resolve(root, "static"), { withFileTypes: true }),
]);
const config = JSON.parse(configSource);
assert.equal(config.version, 3, "Expected genuine Build Output API v3.");
assert.deepEqual(emitted, generated, "Vercel emitted CSS differs from canonical generated bytes.");
const sum = data => createHash("sha256").update(data).digest("hex");
const stableFilename = "styles-runtime.css";
const hashPathPattern = /^styles-runtime\.[0-9a-f]{64}\.css$/;
const hashedFiles = topFiles.filter(f => f.isFile() && hashPathPattern.test(f.name)).map(f => f.name);
const overrides = config.overrides && typeof config.overrides === "object" ? config.overrides : {};
const selectedOverrides = Object.entries(overrides)
  .filter(([path]) => /(styles-runtime\.css|index\.html|release\.json|app-core-runtime\.js)/.test(path))
  .map(([path, rule]) => ({ path, keys: Object.keys(rule || {}).sort() }));
const report = {
  test: "PERF-04B actual Vercel build-only static asset identity",
  buildOutputVersion: config.version,
  cssFilename: stableFilename,
  emittedCssBytes: emitted.length,
  generatedCssBytes: generated.length,
  sha256: sum(emitted),
  hashedCssFilesPresent: hashedFiles,
  selectedOverrideKeys: selectedOverrides,
  conclusion: hashedFiles.length === 0
    ? "Emitted CSS exists only under stable stylesheet name; no retained hash-addressed stylesheet path found in current build."
    : "Hashed CSS candidates exist; prove availability across multiple releases and final CDN headers before immutable.",
  limit: "Actual local prebuilt artifact, not a deployed CDN response; future releases could alter asset availability.",
};
console.log(JSON.stringify(report));
